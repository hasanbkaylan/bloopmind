// Rasterised icons for the canvas (cached per icon + tone).
const iconCache = new Map();
function iconImg(key, tone) {
  const id = key + tone;
  let e = iconCache.get(id);
  if (e) return e.ok ? e.img : null;
  const img = new Image();
  e = { img, ok: false };
  img.onload = () => { e.ok = true; };
  const col = tone === 'w' ? '#ffffff' : '#12172a';
  img.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(
    `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 24 24" fill="none" stroke="${col}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${(ICON_MAP[key] || ICON_MAP.bell).body}</svg>`);
  iconCache.set(id, e);
  return null;
}
